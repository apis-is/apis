#!/bin/bash

# This script generates a js file that imports all the `.js` files in the `endpoints` directory (deep)

directory="endpoints"
output="endpoints/index.js"

# Remove the existing index.js file
rm -f $output

# Add the imports to the new index.js file
{
  echo "/* eslint-disable */"
  echo "// This file is auto-generated. Do not edit this file manually."
  echo ""
} >> $output

# Import all the files in the directory, excluding `tests` folders
find $directory -type f -name '*.js' ! -path "*/tests/*" | while read -r file; do
  echo "import './$(echo "$file" | sed 's/endpoints\///')';" >> $output
done

echo "Generated $output"
